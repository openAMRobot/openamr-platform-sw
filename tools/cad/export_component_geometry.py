"""Export reusable component envelopes from the existing CAD map, without a second specification."""
import argparse
import hashlib
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'tools/cad/base_mesh_map.yaml'
TARGET = ROOT / 'ros2/src/openamrobot_description/config/component_geometry.yaml'


def rendered():
    source = yaml.safe_load(SOURCE.read_text())
    component = source['components']['estop']
    data = dict(source='tools/cad/base_mesh_map.yaml',
                source_sha256=hashlib.sha256(SOURCE.read_bytes()).hexdigest(),
                units='mm', estop={k: component[k] for k in
                                  ['bom', 'placeholder', 'placeholder_note', 'dimension_source', 'parts']})
    for name in ['hub_motor_wheel', 'castor']:
        data[name] = {k: source['components'][name][k] for k in ['dimension_source', 'parts']}
    return '# Generated by tools/cad/export_component_geometry.py; do not edit.\n' + yaml.safe_dump(data, sort_keys=False)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != rendered():
            raise SystemExit('component_geometry.yaml is stale; run tools/cad/export_component_geometry.py')
        print('component geometry matches the CAD map')
    else:
        TARGET.write_text(rendered())
